package top.mobilegl.plugin.config

import android.content.Context
import android.os.Build
import android.os.Environment
import java.io.File

/**
 * Writes the key=value file the native ConfigLoader reads before libMobileGL starts.
 *
 * The game process is the launcher's process, so the file has to live on shared storage:
 * /sdcard/MobileGL/runtime.conf. On Android 11+ that requires "all files access"; when the
 * user has not granted it we still write a private copy and report the fallback path.
 *
 * The native side reads MOBILEGL_CONFIG_FILE first, then this default path. The proxy also
 * exports these values into the game process so the file stays authoritative for the plugin UI.
 */
class RuntimeConfigWriter(private val context: Context) {
    data class Status(
        val sharedPath: String,
        val sharedWritten: Boolean,
        val privatePath: String,
        val privateWritten: Boolean,
        val reason: String? = null,
    )

    fun write(config: PluginConfig): Status {
        val text = buildString {
            appendLine("# Generated by MobileGL Plugin. Do not edit while Minecraft is running.")
            appendLine("# Keys use the same names as MobileGL environment variables.")
            val entries = LinkedHashMap(config.env)
            entries["MOBILEGL_BACKEND_TYPE"] = config.backend
            entries.forEach { (key, value) ->
                if (key.matches(Regex("[A-Z][A-Z0-9_]{1,63}"))) {
                    appendLine(key + "=" + value)
                }
            }
            // Read by libRendererProxy.so before the launcher starts the game.
            appendLine("RENDERER_MODE=" + if (config.sfpewEnabled) "sfpew" else "direct")
            config.activeRendererLibPath?.takeIf { it.isNotBlank() }?.let { appendLine("RENDERER_SO=" + it) }
        }

        val shared = File("/sdcard/MobileGL/runtime.conf")
        var sharedWritten = false
        var reason: String? = null
        try {
            shared.parentFile?.mkdirs()
            shared.writeText(text)
            sharedWritten = true
        } catch (t: Throwable) {
            reason = if (!hasAllFilesAccess()) {
                "未授予“所有文件访问权限”，共享路径不可写"
            } else {
                t.message ?: t.toString()
            }
        }

        val private = File(context.filesDir, "plugin/runtime.conf")
        var privateWritten = false
        try {
            private.parentFile?.mkdirs()
            private.writeText(text)
            privateWritten = true
        } catch (_: Throwable) {
        }

        return Status(
            sharedPath = shared.absolutePath,
            sharedWritten = sharedWritten,
            privatePath = private.absolutePath,
            privateWritten = privateWritten,
            reason = reason,
        )
    }

    fun readShared(): String? {
        val shared = File("/sdcard/MobileGL/runtime.conf")
        return runCatching { if (shared.isFile) shared.readText() else null }.getOrNull()
    }

    fun writeRaw(text: String): Status {
        var sharedWritten = false
        var reason: String? = null
        val shared = File("/sdcard/MobileGL/runtime.conf")
        try {
            shared.parentFile?.mkdirs()
            shared.writeText(text)
            sharedWritten = true
        } catch (t: Throwable) {
            reason = if (!hasAllFilesAccess()) "未授予“所有文件访问权限”，共享路径不可写" else t.message
        }
        val privateFile = File(context.filesDir, "plugin/runtime.conf")
        val privateWritten = runCatching { privateFile.parentFile?.mkdirs(); privateFile.writeText(text); true }.getOrDefault(false)
        return Status(shared.absolutePath, sharedWritten, privateFile.absolutePath, privateWritten, reason)
    }

    fun hasAllFilesAccess(): Boolean {
        return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            Environment.isExternalStorageManager()
        } else {
            true
        }
    }
}